import type { TileCode } from '../domain/tiles'

export interface RuleChoice { id: string; label: string; correct: boolean; explanation: string }
export interface RuleQuestion {
  id: string
  prompt: string
  note?: string
  tiles?: readonly TileCode[]
  river?: readonly TileCode[]
  doraIndicator?: TileCode
  selectionMode?: 'single' | 'multiple'
  choices: readonly RuleChoice[]
}
export interface RuleLesson {
  id: string
  phaseId: string
  order: number
  title: string
  subtitle: string
  intro: string
  habit: string
  difference: string
  keyPoint: string
  points: readonly string[]
  terms: string
  example?: { label: string; tiles: readonly TileCode[]; caption: string }
  sessionSize?: number
  poolLabel?: string
  questions: readonly RuleQuestion[]
}
export interface RulePhase { id: string; eyebrow: string; title: string; goal: string; lessonIds: readonly string[] }
type QuestionVisual = Pick<RuleQuestion, 'tiles' | 'river' | 'doraIndicator' | 'note'>

function binary(id: string, prompt: string, correctLabel: string, wrongLabel: string, explanation: string, visual: Partial<QuestionVisual> = {}): RuleQuestion {
  return { id, prompt, ...visual, choices: [
    { id: 'yes', label: correctLabel, correct: true, explanation },
    { id: 'no', label: wrongLabel, correct: false, explanation },
  ] }
}

function choose(id: string, prompt: string, correctLabel: string, wrongLabels: readonly string[], explanation: string, visual: Partial<QuestionVisual> = {}): RuleQuestion {
  return { id, prompt, ...visual, choices: [
    { id: 'correct', label: correctLabel, correct: true, explanation },
    ...wrongLabels.map((label, index) => ({ id: `wrong-${index}`, label, correct: false, explanation })),
  ] }
}

